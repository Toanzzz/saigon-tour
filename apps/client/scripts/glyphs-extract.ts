/**
 * Extracts the glyph icons the UI uses from `@iconify-json/glyphs` into a typed
 * module, so only the referenced icons ship in the bundle. Re-run after editing
 * the `USED` list or bumping the package:
 *   bun scripts/glyphs-extract.ts
 */

import { writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const here = dirname(fileURLToPath(import.meta.url))

type IconSet = {
  width?: number
  height?: number
  icons: Record<string, { body: string; width?: number; height?: number }>
}
const set = require('@iconify-json/glyphs/icons.json') as IconSet

/** Glyph icon names the client renders via <Glyph>. */
const USED = ['male', 'female'] as const

const entries = USED.map((name) => {
  const icon = set.icons[name]
  if (!icon) throw new Error(`glyphs: missing icon "${name}"`)
  return {
    name,
    body: icon.body,
    width: icon.width ?? set.width ?? 24,
    height: icon.height ?? set.height ?? 24,
  }
})

const body = entries
  .map(
    (e) =>
      `  ${e.name}: { body: ${JSON.stringify(e.body)}, width: ${e.width}, height: ${e.height} },`
  )
  .join('\n')

const out = `// Generated by scripts/glyphs-extract.ts from @iconify-json/glyphs. Do not edit.
export type GlyphName = ${USED.map((n) => `'${n}'`).join(' | ')}

export const GLYPHS: Record<GlyphName, { body: string; width: number; height: number }> = {
${body}
}
`

const target = resolve(here, '../src/shared/ui/glyphs.generated.ts')
await writeFile(target, out)
